/* ==========================================================================
   SERVICE WORKER — SERVICIO MÉDICO JUAN PABLO II (PWA ANDROID & APPLE iOS)
   Caché estática 100 % segura: solo recursos públicos de la interfaz.
   CERO almacenamiento de datos clínicos o personales de pacientes.
   ========================================================================== */
const CACHE_NAME = 'jpii-mobile-pwa-v1';
const PRECACHE_URLS = [
  './',
  './app.html',
  './index.html',
  './manifest.webmanifest',
  './assets/hero-jpii.webp',
  './assets/logo-mini-jpii.webp',
  './assets/logo-mini-jpii.png',
  './assets/diagnostico-lab.webp',
  './assets/icon-180.png',
  './assets/icon-192.png',
  './assets/icon-512.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          return response;
        })
        .catch(() => caches.match(request).then((cached) => cached || caches.match('./app.html')))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response && response.status === 200) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    })
  );
});
